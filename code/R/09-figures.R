## ---- F-ensemble-shrink : three histograms, and what the standard repair does ----
ensemble_shrink_data <- local({
  set.seed(11)
  P <- 4000; s2 <- 1; se2 <- 0.6
  th <- rnorm(P, 0, sqrt(s2)); hat <- th + rnorm(P, 0, sqrt(se2))
  w <- s2 / (s2 + se2); eap <- w * hat
  set.seed(181)
  Q <- 20000; sev <- 0.55
  tb <- ifelse(runif(Q) < .5, rnorm(Q, -1, .35), rnorm(Q, 1, .35))
  tb <- (tb - mean(tb)) / sd(tb)
  hb <- tb + rnorm(Q, 0, sqrt(sev))
  s2b <- var(tb); wb <- s2b / (s2b + sev)
  eb <- wb * hb; post_var <- wb * sev
  ab <- sqrt(1 + (1 - 1/Q) * mean(post_var) / mean((eb - mean(eb))^2))
  cb <- mean(eb) + (eb - mean(eb)) * ab
  list(P = P, s2 = s2, se2 = se2, th = th, hat = hat, w = w, eap = eap,
       Q = Q, sev = sev, tb = tb, hb = hb, wb = wb, eb = eb, cb = cb)
})
excess_kurtosis <- function(x) mean((x - mean(x))^4) / sd(x)^4 - 3
empirical_ks <- function(x, truth) {
  at <- sort(unique(c(x, truth)))
  max(abs(ecdf(x)(at) - ecdf(truth)(at)))
}
ensemble_shrink_summary <- with(ensemble_shrink_data, data.frame(
  metric = c("latent_variance", "error_variance_left", "shrinkage_weight_left",
             "error_variance_bimodal", "true_sd", "posterior_mean_sd", "cb_sd",
             "true_excess_kurtosis", "posterior_mean_excess_kurtosis",
             "cb_excess_kurtosis", "ks_ml", "ks_posterior_mean", "ks_cb"),
  value = c(s2, se2, w, sev, sd(tb), sd(eb), sd(cb), excess_kurtosis(tb),
            excess_kurtosis(eb), excess_kurtosis(cb), empirical_ks(hb, tb),
            empirical_ks(eb, tb), empirical_ks(cb, tb)),
  stringsAsFactors = FALSE))
save_figure_data(ensemble_shrink_summary, "F-ensemble-shrink-summary")


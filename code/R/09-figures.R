draw_rank_rel <- function() {
  curves <- rank_rel_fine$curves
  gaps <- rank_rel_fine$gaps
  near <- rank_rel_fine$near_ties
  op <- par(mfrow = c(1, 2), mar = c(4.3, 4.4, 2.6, 0.8), cex.axis = .9, cex.main = .96)

  plot(NA, xlim = range(curves$wbar), ylim = range(curves$concordance),
       xlab = expression(bar(w)), ylab = "pairwise rank concordance",
       main = "Reliability is the leading driver")
  for (k in seq_along(rank_shape_names)) {
    z <- curves[curves$shape == rank_shape_names[k], ]
    lines(z$wbar, z$concordance, col = PAL[k], lwd = 2.4, type = "b", pch = 16, cex = .55)
  }
  legend("topleft", bty = "n", cex = .76, lwd = 2.4,
         col = PAL[seq_along(rank_shape_names)], legend = rank_shape_names)

  plot(gaps$wbar, gaps$gap, type = "l", lwd = 2.6, col = PAL[2],
       xlab = expression("matched "*bar(w)), ylab = "spread across the four shapes",
       ylim = c(0, max(gaps$gap) * 1.18), main = "Shape gap peaks, then declines")
  imax <- which.max(gaps$gap)
  points(gaps$wbar[imax], gaps$gap[imax], pch = 16, col = PAL[2], cex = 1.0)
  abline(h = 0, col = "grey85")
  legend("topleft", bty = "n", cex = .74,
         legend = c("near-tie mass, P(|diff| < 0.25):",
                    paste0("  ", near$shape, ": ", sprintf("%.3f", near$near_tie_mass))))
  par(op)
}

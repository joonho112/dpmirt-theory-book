## ---- F-stein : the James-Stein risk, and where the gain actually is ----
## Risk from James & Stein (1961, sec. 2): rho = p - (p-2)^2 E_K[1/(p-2+2K)],
## K ~ Poisson(||xi||^2 / 2). Verified against the two values they state:
## rho = 2 at xi = 0 and rho -> p as ||xi||^2 -> infinity. Deterministic.
draw_stein <- function() {
  js_risk <- function(p, s2) {                     # s2 = ||xi||^2
    lam <- s2 / 2
    k <- 0:max(200L, ceiling(lam + 12 * sqrt(lam + 1)))
    p - (p - 2)^2 * sum(dpois(k, lam) / (p - 2 + 2 * k))
  }
  ps <- c(3, 10, 200)
  op <- par(mfrow = c(1, 2), mar = c(4.3, 4.4, 2.4, 0.8), cex.axis = .9)

  s2 <- seq(0, 60, length.out = 121)
  plot(NA, xlim = c(0, 60), ylim = c(0, 1.05), xlab = expression("||"*xi*"||"^2),
       ylab = "risk / p", main = "James-Stein risk, relative to p")
  abline(h = 1, col = PAL[5], lwd = 2)
  for (k in seq_along(ps)) {
    r <- vapply(s2, js_risk, numeric(1), p = ps[k])
    lines(s2, r / ps[k], col = PAL[k], lwd = 2.4)
  }
  legend("bottomright", bty = "n", cex = .82,
         lwd = c(2.4, 2.4, 2.4, 2), col = c(PAL[1:3], PAL[5]),
         legend = c("p = 3", "p = 10", "p = 200", "usual estimator"))

  ## per-coordinate spread is what matters: ||xi||^2 = p * (mean squared coordinate)
  m2 <- seq(0, 3, length.out = 121)
  plot(NA, xlim = c(0, 3), ylim = c(0, 1.05), xlab = expression("||"*xi*"||"^2/p),
       ylab = "risk / p", main = "Against spread per coordinate")
  abline(h = 1, col = PAL[5], lwd = 2)
  for (k in seq_along(ps)) {
    r <- vapply(m2 * ps[k], js_risk, numeric(1), p = ps[k])
    lines(m2, r / ps[k], col = PAL[k], lwd = 2.4)
  }
  abline(v = 1, col = "grey85", lty = 3)
  par(op)
}
save_fig("F-stein", paste(
  "The risk of the James--Stein estimator @eq-james-stein relative to the risk $p$ of the",
  "usual estimator, computed from the expression James and Stein give in their § 2.",
  "Left: against $\\|\\xi\\|^2$. The curve starts at $2/p$ — a hundredfold improvement at",
  "$p=200$ — and climbs toward 1, and the larger $p$ is the more slowly it climbs.",
  "Right: the same curves against $\\|\\xi\\|^2/p$, the mean squared coordinate, which is",
  "the quantity that is comparable across dimensions; the dotted line marks a unit",
  "population variance. Read at $\\|\\xi\\|^2/p = 1$ the gain is modest for $p=3$ and",
  "still substantial for $p=200$. Dimension determines the inadmissibility threshold,",

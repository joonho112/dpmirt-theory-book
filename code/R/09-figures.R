## ---- F-three-goals : the three ensembles, and what each is optimal for ----
## Deterministic: independent normal posteriors, everything by quadrature.
draw_three_goals <- function() {
  eta <- c(-1.6, -0.9, -0.4, -0.1, 0.2, 0.6, 1.1, 1.8)
  lam <- c(0.50, 0.40, 0.35, 0.30, 0.30, 0.35, 0.45, 0.60); K <- length(eta)
  g <- seq(-6, 6, length.out = 6001)
  Gbar <- vapply(g, function(t) mean(pnorm(t, eta, sqrt(lam))), numeric(1))
  Uhat <- approxfun(Gbar, g, ties = "ordered", rule = 2)((2 * (1:K) - 1) / (2 * K))
  Rbar <- vapply(seq_len(K), function(k) sum(vapply(seq_len(K), function(q)
    if (q == k) 1 else pnorm(0, eta[q] - eta[k], sqrt(lam[k] + lam[q])), numeric(1))),
    numeric(1))
  if (anyDuplicated(round(Rbar, 12)))
    stop("F-three-goals requires distinct expected ranks; exact ties need randomized refinement")
  gr <- Uhat[rank(Rbar, ties.method = "min")]
  a  <- sqrt(1 + mean(lam) / (sum((eta - mean(eta))^2) / (K - 1)))
  cb <- mean(eta) + a * (eta - mean(eta))
  op <- par(mfrow = c(1, 2), mar = c(4.3, 4.4, 2.6, 0.8), cex.axis = .9, cex.main = .96)

  plot(g, Gbar, type = "l", lwd = 2.6, col = PAL[5], xlim = c(-3.2, 3.2),
       xlab = expression(t), ylab = expression(bar(G)[K](t)),
       main = expression(bar(G)[K](t)*" is a probability"))
  segments(-6, (2*(1:K)-1)/(2*K), Uhat, (2*(1:K)-1)/(2*K), col = "grey80", lty = 3)
  segments(Uhat, 0, Uhat, (2*(1:K)-1)/(2*K), col = PAL[3], lty = 3)
  points(Uhat, (2*(1:K)-1)/(2*K), pch = 16, col = PAL[3], cex = 1.1)
  points(0, mean(pnorm(0, eta, sqrt(lam))), pch = 4, cex = 1.5, lwd = 2.4, col = PAL[2])
  text(0.15, mean(pnorm(0, eta, sqrt(lam))) - 0.07, adj = 0, cex = .82, col = PAL[2],
       labels = sprintf("Gbar(0) = %.3f", mean(pnorm(0, eta, sqrt(lam)))))
  legend("topleft", bty = "n", cex = .8, lwd = c(2.6, NA), pch = c(NA, 16),
         col = c(PAL[5], PAL[3]),
         legend = c(expression(bar(G)[K]), expression("mass points "*hat(U)[j])))

  plot(NA, xlim = c(0.6, 3.4), ylim = range(c(eta, cb, gr)) + c(-.25, .25),
       xaxt = "n", xlab = "", ylab = expression(theta), main = "Three ensembles, same ranks")
  axis(1, at = 1:3, labels = c("PM", "CB", "GR"), cex.axis = 1.05)
  for (k in seq_len(K)) lines(1:3, c(eta[k], cb[k], gr[k]), col = "grey78")
  points(rep(1, K), eta, pch = 16, col = PAL[1], cex = 1.1)
  points(rep(2, K), cb,  pch = 16, col = PAL[3], cex = 1.1)
  points(rep(3, K), gr,  pch = 16, col = PAL[2], cex = 1.1)
  sv <- function(x) sum((x - mean(x))^2) / (K - 1)
  mtext(sprintf("sample variance %.2f / %.2f / %.2f, target %.2f",
                sv(eta), sv(cb), sv(gr), mean(lam) + sv(eta)), side = 1, line = 2.4, cex = .8)
  par(op)
}

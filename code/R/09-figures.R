## ---- F-tif-msem : test information, local SEM, and where MSEM comes from ----
draw_tif <- function() {
  th <- seq(-4, 4, length.out = 401)
  set.seed(7)                       # fixed: illustrative, not inferential
  beta <- seq(-1.6, 1.6, length.out = 20)     # 20 items, moderately targeted
  info <- function(t) sum(plogis(t - beta) * (1 - plogis(t - beta)))
  J  <- vapply(th, info, numeric(1))
  se <- 1 / sqrt(J)
  op <- par(mfrow = c(1, 2), mar = c(4.2, 4.3, 2.4, 0.8), cex.axis = .9)

  plot(th, J, type = "l", lwd = 2.4, col = PAL[1], xlab = expression(theta),
       ylab = expression(J(theta)), main = "Test information")
  rug(beta, col = PAL[5]); abline(v = range(beta), col = "grey88", lty = 3)

  plot(th, se, type = "l", lwd = 2.4, col = PAL[2], ylim = c(0, 1.6),
       xlab = expression(theta), ylab = expression(se(hat(theta))),
       main = "Local standard error")
  abline(v = range(beta), col = "grey88", lty = 3)
  ## MSEM under a standard normal G, and its root
  w  <- dnorm(th); w <- w / sum(w)
  msem <- sum(w * se^2); rmsem <- sqrt(msem)
  mean_se <- sum(w * se)
  abline(h = rmsem,   col = PAL[3], lwd = 2, lty = 2)
  abline(h = mean_se, col = PAL[4], lwd = 2, lty = 4)
  legend("top", bty = "n", cex = .8, lwd = c(2, 2), lty = c(2, 4),
         col = c(PAL[3], PAL[4]),
         legend = c(sprintf("RMSEM = %.3f", rmsem),
                    sprintf("mean se = %.3f", mean_se)))
  par(op)
}
save_fig("F-tif-msem", paste(
  "Test information (left) and the local standard error it implies (right), for a",
  "20-item Rasch test with difficulties evenly spaced on $[-1.6, 1.6]$ (tick marks).",
  "Information is additive over items and peaks where the items sit; the standard error",
  "is the reciprocal square root and rises steeply outside the range the items cover.",
  "The two horizontal lines average the right-hand curve against a standard normal $G$:",
  "RMSEM averages on the variance scale and then takes a root, the mean standard error",
  "averages on the standard-error scale, and the first exceeds the second by",
  "@prp-msem-jensen. Seed fixed; illustrative, no inference rests on it.",
  "Generated by code/R/09-figures.R."),
  draw_tif)

## ---- F-jensen : the three marginal functionals, and how far apart they are ----
## Deterministic quadrature; no simulation, no seed.
draw_jensen <- function() {
  Jf <- function(b) function(t)
    vapply(t, function(z) sum(plogis(z - b) * (1 - plogis(z - b))), numeric(1))
  gdens <- list(
    normal  = function(t) dnorm(t),
    heavy   = function(t) dt(t / sqrt(3), df = 3),
    skew    = function(t) 0.75 * dnorm(t, -0.6, 0.5) + 0.25 * dnorm(t, 1.8, 0.9),
    bimodal = function(t) 0.5 * dnorm(t, -1.2, 0.5) + 0.5 * dnorm(t, 1.2, 0.5))
  ## every G is standardized to mean 0, variance 1 before use, so the three
  ## functionals are compared on the same latent-variance basis.
  trio <- function(I, gfun) {
    b  <- seq(-1.6, 1.6, length.out = I)
    t  <- seq(-12, 12, length.out = 6001)
    w  <- gfun(t); w <- w / sum(w)
    mu <- sum(w * t); s <- sqrt(sum(w * (t - mu)^2))
    tz <- (t - mu) / s; k <- abs(tz) < 8
    tz <- tz[k]; w <- w[k] / sum(w[k])
    J  <- Jf(b)(tz)
    c(wbar = 1 / (1 + sum(w / J)),
      rTh  = sum(w * J / (J + 1)),
      rTil = sum(w * J) / (sum(w * J) + 1))
  }
  Igrid <- c(5, 8, 12, 18, 25, 35, 50, 70, 95)
  op <- par(mfrow = c(1, 2), mar = c(4.2, 4.4, 2.4, 0.8), cex.axis = .9)

  z <- t(vapply(Igrid, trio, numeric(3), gfun = gdens$normal))
  plot(NA, xlim = c(0.35, 0.98), ylim = c(0, 0.010), xlab = expression(bar(w)),
       ylab = "distance above w-bar", main = "The sandwich, normal G")
  polygon(c(z[, "wbar"], rev(z[, "wbar"])),
          c(z[, "rTil"] - z[, "wbar"], rev(z[, "rTh"] - z[, "wbar"])),
          col = "#D55E0022", border = NA)
  polygon(c(z[, "wbar"], rev(z[, "wbar"])),
          c(z[, "rTh"] - z[, "wbar"], rep(0, nrow(z))),
          col = "#009E7322", border = NA)
  lines(z[, "wbar"], z[, "rTil"] - z[, "wbar"], col = PAL[2], lwd = 2.4)
  lines(z[, "wbar"], z[, "rTh"]  - z[, "wbar"], col = PAL[3], lwd = 2.4, lty = 2)
  abline(h = 0, col = PAL[5], lwd = 2)
  legend("topright", bty = "n", cex = .8, lwd = c(2.4, 2.4, 2), lty = c(1, 2, 1),
         col = c(PAL[2], PAL[3], PAL[5]),
         legend = c(expression(tilde(rho)), expression(rho[Theta]), expression(bar(w))))

  plot(NA, xlim = c(0.35, 0.98), ylim = c(0, 0.032), xlab = expression(bar(w)),
       ylab = expression(tilde(rho) - bar(w)), main = "Outer gap, by shape of G")
  for (k in seq_along(gdens)) {
    zz <- t(vapply(Igrid, trio, numeric(3), gfun = gdens[[k]]))
    lines(zz[, "wbar"], zz[, "rTil"] - zz[, "wbar"], col = PAL[k], lwd = 2.4)
  }
  legend("topright", bty = "n", cex = .8, lwd = 2.4, col = PAL[seq_along(gdens)],
         legend = c("normal", "heavy-tailed (t3)", "skewed", "bimodal"))
  par(op)
}
save_fig("F-jensen", paste(
  "The three marginal reliability functionals of @sec-ch08-functionals, over Rasch tests",
  "of 5 to 95 items with difficulties evenly spaced on $[-1.6,1.6]$. Left: the two",
  "functionals plotted as distances above $\\bar w$, so the sandwich is visible;",
  "$\\rho_\\Theta$ lies strictly between the other two everywhere, and the inner gap is",
  "roughly half the outer one. Note the vertical scale. Right: the outer gap",
  "$\\tilde\\rho-\\bar w$ under four latent distributions, each standardized to variance 1.",
  "Heavy tails widen the gap and bimodality narrows it relative to the normal, because",
  "the gap tracks how much information varies over the mass of $G$, not how far $G$ is",
  "from normal. Every gap here is below 0.03. Deterministic quadrature; no simulation.",
  "Generated by code/R/09-figures.R."),
  draw_jensen)

## ---- F-rel-items : the inverse design problem, and the difficulty-spread lever ----
## Population forward map w-bar(I, beta) = 1/(1 + E_G[J(theta)^-1]) under theta ~ N(0,1)
## with item parameters KNOWN. This is the asymptotic analogue of the manuscript's
## Monte Carlo search, not a re-run of it; the offset between the two is the subject
## of ch. 9 sec. 4. Each replicate draws one ordered 400-item bank. Every candidate
## length uses a prefix of that same bank, so the objective cannot change mid-search.
q_rel <- seq(-5, 5, length.out = 401)
gw_rel <- dnorm(q_rel); gw_rel <- gw_rel / sum(gw_rel)
tg_rel <- seq(0.45, 0.92, by = 0.01)
sds_rel <- c(0.5, 1.0, 1.5)
R_rel <- 120L
rel_curve <- function(bank) {
  pp <- plogis(outer(q_rel, bank, "-"))
  jcum <- t(apply(pp * (1 - pp), 1L, cumsum))
  1 / (1 + colSums(gw_rel / jcum))
}
set.seed(20260804)
rel_draws <- lapply(sds_rel, function(s) {
  z <- replicate(R_rel, {
    curve <- rel_curve(rnorm(400L, 0, s))
    vapply(tg_rel, function(target) {
      hit <- which(curve >= target)
      if (length(hit)) hit[1L] else NA_integer_
    }, integer(1))
  })
  rowMeans(z)
})
rel_summary <- data.frame(
  target = rep(tg_rel, times = length(sds_rel)),
  sd_beta = rep(sds_rel, each = length(tg_rel)),
  mean_items = unlist(rel_draws),
  replicates = R_rel,
  max_bank = 400L,
  seed = 20260804L
)
saveRDS(rel_summary, file.path(paths$tables, "F-rel-items-summary.rds"))
write.csv(rel_summary, file.path(paths$tables, "supplement", "F-rel-items-summary.csv"),

## colour-blind-safe, consistent with the DPMirt package palette
PAL <- c("#0072B2", "#D55E00", "#009E73", "#CC79A7", "#666666")

save_fig <- function(id, caption, draw, w = 7.2, h = 4.2) {
  png(file.path(FIG, paste0(id, ".png")), width = w, height = h,
      units = "in", res = 300); draw(); dev.off()
  pdf(file.path(FIG, paste0(id, ".pdf")), width = w, height = h,
      timestamp = FALSE, producer = FALSE); draw(); dev.off()
  writeLines(caption, file.path(FIG, paste0(id, ".md")))
  cat(sprintf("  %-22s png + pdf + caption\n", id))
}

save_figure_data <- function(obj, id) {
  saveRDS(obj, file.path(paths$tables, paste0(id, ".rds")))
  write.csv(obj, file.path(paths$tables, "supplement", paste0(id, ".csv")),
            row.names = FALSE, na = "")
}

irf <- function(theta, beta, lambda) plogis(lambda * (theta - beta))

## ---- F-irf : item response functions and item information ---------------
draw_irf <- function() {
  th <- seq(-4, 4, length.out = 401)
  op <- par(mfrow = c(1, 2), mar = c(4.2, 4.2, 2.4, 0.8), cex.axis = .9)
  spec <- list(c(0, 1), c(-1, 1), c(0, 2), c(0, 0.5))
  labs <- c(expression(beta==0*","~lambda==1), expression(beta==-1*","~lambda==1),
            expression(beta==0*","~lambda==2), expression(beta==0*","~lambda==0.5))
  plot(NA, xlim = c(-4, 4), ylim = c(0, 1), xlab = expression(theta),
       ylab = "P(correct)", main = "Item response function")
  abline(h = 0.5, col = "grey85"); abline(v = 0, col = "grey85")
  for (k in seq_along(spec))
    lines(th, irf(th, spec[[k]][1], spec[[k]][2]), col = PAL[k], lwd = 2.2)
  legend("bottomright", legend = labs, col = PAL[1:4], lwd = 2.2, bty = "n", cex = .85)

  plot(NA, xlim = c(-4, 4), ylim = c(0, 1.05), xlab = expression(theta),
       ylab = "item information", main = "Item information")
  abline(v = 0, col = "grey85")
  for (k in seq_along(spec)) {
    p <- irf(th, spec[[k]][1], spec[[k]][2])
    lines(th, spec[[k]][2]^2 * p * (1 - p), col = PAL[k], lwd = 2.2)
  }
  par(op)
}

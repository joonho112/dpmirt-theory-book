## ---- F-flexible-g : representational capacity, not estimation performance ----
## Each family's best approximation to one target density, by minimizing KL on a
## fixed grid. This says what a family CAN represent given unlimited data; it says
## nothing about how well any of them is estimated. Deterministic (fixed starts).
draw_flexg <- function() {
  x  <- seq(-4, 4, length.out = 1201); dx <- x[2] - x[1]
  ## target: skewed AND bimodal, standardized to mean 0 variance 1
  raw <- 0.62 * dnorm(x, -0.7, 0.45) + 0.38 * dnorm(x, 1.15, 0.75)
  w0  <- raw / sum(raw); mu <- sum(w0 * x); sd0 <- sqrt(sum(w0 * (x - mu)^2))
  tgt <- approxfun((x - mu) / sd0, raw * sd0, rule = 2)(x)
  tgt <- tgt / (sum(tgt) * dx)

  kl <- function(q) { q <- pmax(q, 1e-12); q <- q / (sum(q) * dx)
                      sum(tgt * log(pmax(tgt, 1e-12) / q)) * dx }
  ## normal: KL is minimized by moment matching
  fit_n <- dnorm(x, 0, 1)
  ## skew-normal, parameterized by (xi, omega, alpha)
  dsn <- function(p) 2 / p[2] * dnorm((x - p[1]) / p[2]) * pnorm(p[3] * (x - p[1]) / p[2])
  fit_s <- dsn(optim(c(-0.5, 1.2, 2), function(p)
    if (p[2] <= 0.05) 1e6 else kl(dsn(p)), control = list(maxit = 3000))$par)
  ## K-component normal mixture with equal-ish weights estimated on the logit scale
  mix <- function(p, K) {
    w <- exp(c(0, p[1:(K - 1)])); w <- w / sum(w)
    m <- p[K:(2 * K - 1)]; s <- exp(p[(2 * K):(3 * K - 1)])
    rowSums(vapply(seq_len(K), function(k) w[k] * dnorm(x, m[k], s[k]), numeric(length(x))))
  }
  fit_mix <- function(K, start) mix(optim(start, function(p) kl(mix(p, K)),
                                          control = list(maxit = 8000))$par, K)
  fit_2 <- fit_mix(2, c(0, -0.7, 0.9, log(0.5), log(0.7)))
  fit_5 <- fit_mix(5, c(rep(0, 4), seq(-1.6, 1.6, length.out = 5), rep(log(0.45), 5)))

  op <- par(mar = c(4.2, 4.3, 2.4, 0.8), cex.axis = .9)
  plot(x, tgt, type = "l", lwd = 3.2, col = PAL[5], xlim = c(-3, 3),
       ylim = c(0, max(tgt) * 1.12), xlab = expression(theta), ylab = "density",
       main = "Best approximation to one target, by family")
  lines(x, fit_n, col = PAL[1], lwd = 2.2, lty = 2)
  lines(x, fit_s, col = PAL[2], lwd = 2.2)
  lines(x, fit_2, col = PAL[3], lwd = 2.2)
  lines(x, fit_5, col = PAL[4], lwd = 2.2, lty = 3)
  legend("topright", bty = "n", cex = .82, lwd = c(3.2, 2.2, 2.2, 2.2, 2.2),
         lty = c(1, 2, 1, 1, 3), col = c(PAL[5], PAL[1], PAL[2], PAL[3], PAL[4]),
         legend = c("target G",
                    sprintf("normal (KL %.3f)", kl(fit_n)),
                    sprintf("skew-normal (KL %.3f)", kl(fit_s)),
                    sprintf("2-component mixture (KL %.3f)", kl(fit_2)),
                    sprintf("5-component mixture (KL %.3f)", kl(fit_5))))
  par(op)
}
save_fig("F-flexible-g", paste(
  "What each family of latent-trait distributions **can represent**, shown as its best",
  "approximation to one skewed and bimodal target, obtained by minimizing",
  "Kullback--Leibler divergence on a fixed grid. The normal can match only location and",
  "scale. The skew-normal captures the asymmetry and cannot produce a second mode at all.",
  "The two-component mixture recovers the target exactly, but only because the target",
  "*is* a two-component normal mixture — the fit is circular and is shown to make the",
  "point that follows. Five components do no better than two because a nonminimal",
  "representation can duplicate or zero out components. This does not refute",
  "identification of the minimal order under standard conditions. @sec-ch14-mixtures",
  "contrasts a fixed order, an MFM prior on population order, and a DPM prior on occupied",
  "partitions.",
  "This figure is about representational capacity given unlimited data. It says nothing",
  "about how well any family is *estimated* from a finite sample, which is where the",
  "families differ most and which @tbl-flexible-g reports separately.",
  "Deterministic; fixed optimizer starts. Generated by code/R/09-figures.R."),
  draw_flexg, w = 6.6, h = 4.4)


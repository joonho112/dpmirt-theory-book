## ---- F-k-alpha : Antoniak's distribution of the number of clusters ----
## Exact PMF from unsigned Stirling numbers of the first kind, on the log scale.
draw_kalpha <- function() {
  log_s1 <- function(n) {
    lg <- 0
    if (n == 1) return(lg)
    for (m in 2:n) {
      prev <- lg; new <- rep(-Inf, m)
      for (k in 1:m) {
        a <- if (k >= 2) prev[k - 1] else -Inf
        b <- if (k <= m - 1) prev[k] + log(m - 1) else -Inf
        new[k] <- if (is.infinite(a) && is.infinite(b)) -Inf else
          max(a, b) + log1p(exp(-abs(a - b)))
      }
      lg <- new
    }
    lg
  }
  pmf <- function(n, alpha) exp(log_s1(n) + (1:n) * log(alpha) -
                                  (lgamma(alpha + n) - lgamma(alpha)))
  op <- par(mfrow = c(1, 2), mar = c(4.3, 4.4, 2.6, 0.8), cex.axis = .9)

  alphas <- c(0.5, 1, 5)
  plot(NA, xlim = c(0, 30), ylim = c(0, 0.42), xlab = expression(K[200]),
       ylab = "prior probability", main = expression("Antoniak's law for "*K[J]*", J = 200"))
  for (k in seq_along(alphas)) {
    p <- pmf(200, alphas[k])
    lines(1:30, p[1:30], type = "h", lwd = 3, col = adjustcolor(PAL[k], 0.75))
  }
  legend("topright", bty = "n", cex = .85, lwd = 3, col = PAL[1:3],
         legend = sapply(alphas, function(a) as.expression(bquote(alpha == .(a)))))

  J <- 10^seq(1, 5, length.out = 60)
  plot(NA, xlim = range(J), ylim = c(0, 62), log = "x", xlab = "J (log scale)",
       ylab = expression(E*"["*K[J]*"]"), main = "Logarithmic growth")
  for (k in seq_along(alphas))
    lines(J, alphas[k] * (digamma(alphas[k] + J) - digamma(alphas[k])),
          col = PAL[k], lwd = 2.4)
  par(op)
}
save_fig("F-k-alpha", paste(
  "Antoniak's distribution of the number of occupied clusters. **Left:** the exact prior",
  "pmf of $K_J$ at $J = 200$, computed from unsigned Stirling numbers of the first kind,",
  "for three concentrations. The distribution is tight — at $\\alpha = 1$ almost all the",
  "mass lies between 2 and 10, a central 95\\% interval — so $\\alpha$ is a strong",
  "statement, not a vague one. **Right:** $\\operatorname{E}[K_J] = \\alpha\\{\\psi(\\alpha+J)-\\psi(\\alpha)\\}$ against",
  "$J$ on a logarithmic axis, where the curves are straight: the number of clusters grows",
  "like $\\alpha\\log J$, so ten times the data buys only $\\alpha\\log 10 \\approx 2.3\\alpha$",
  "more clusters. Deterministic; no simulation. Generated by code/R/09-figures.R."),
  draw_kalpha, w = 7.4, h = 4.2)


## ---- F-nonnormal-shapes : the sum-score fallacy, in both directions ----
## Exact computation throughout. P(X = k | theta) by the Poisson-binomial
## recursion; P(X = k) by quadrature over G. No simulation, no seed.
draw_nonnormal <- function() {
  pbin <- function(p) { d <- 1; for (pi in p) d <- c(d * (1 - pi), 0) + c(0, d * pi); d }
  ss <- function(beta, tq, wq) {
    o <- numeric(length(beta) + 1L)
    for (j in seq_along(tq)) o <- o + wq[j] * pbin(plogis(tq[j] - beta))
    o / sum(o)
  }
  std <- function(dens, n = 4001) {            # standardize G to mean 0, variance 1
    t <- seq(-12, 12, length.out = n); w <- dens(t); w <- w / sum(w)
    mu <- sum(w * t); s <- sqrt(sum(w * (t - mu)^2))
    list(t = (t - mu) / s, w = w, d = w / (diff(t)[1] / s))
  }
  Gn <- std(function(t) dnorm(t))
  Gb <- std(function(t) 0.5 * dnorm(t, -1, 0.30) + 0.5 * dnorm(t, 1, 0.30))

  op <- par(mfrow = c(2, 2), mar = c(4.0, 4.2, 2.6, 0.8), cex.axis = .9, cex.main = 1)

  ## row 1: normal G, skewed score distribution
  plot(Gn$t, Gn$d, type = "l", lwd = 2.4, col = PAL[1], xlim = c(-3.5, 3.5),
       xlab = expression(theta), ylab = "density", main = "G is exactly normal")
  b1 <- rep(-1.5, 5); d1 <- ss(b1, Gn$t, Gn$w)
  barplot(d1, names.arg = 0:5, col = PAL[2], border = "white", ylim = c(0, 0.42),
          xlab = "sum score", ylab = "probability",
          main = "5 easy items: score skew -0.99")

  ## row 2: bimodal G, bell-shaped score distribution
  plot(Gb$t, Gb$d, type = "l", lwd = 2.4, col = PAL[1], xlim = c(-3.5, 3.5),
       xlab = expression(theta), ylab = "density", main = "G is sharply bimodal")
  lines(Gn$t, Gn$d, col = "grey75", lwd = 1.6, lty = 2)
  b2 <- seq(-2.5, 2.5, length.out = 6)
  d2 <- ss(b2, Gb$t, Gb$w); d2n <- ss(b2, Gn$t, Gn$w)
  bp <- barplot(d2, names.arg = 0:6, col = PAL[3], border = "white", ylim = c(0, 0.34),
                xlab = "sum score", ylab = "probability",
                main = "6 spread items: TV from normal G = 0.035")
  points(bp, d2n, pch = 18, cex = 1.5, col = PAL[5])
  legend("topright", bty = "n", cex = .8, pch = c(15, 18), col = c(PAL[3], PAL[5]),
         legend = c("under bimodal G", "under normal G"))
  par(op)
}
